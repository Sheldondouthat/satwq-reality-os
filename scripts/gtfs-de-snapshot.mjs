#!/usr/bin/env node
/**
 * Build and publish the gtfs.de German realtime-transit snapshot for the Pages deploy.
 *
 * https://realtime.gtfs.de/realtime-free.pb is a GTFS-RT protobuf feed
 * (~9–14 MB, regenerated ~every 10 s) carrying TripUpdates + Alerts only
 * (NO VehiclePositions). Pulling 10+ MB through the edge on every cache miss
 * is infeasible — and protobuf decode at the edge is disallowed — so the
 * /api/gtfs-de provider (server/providers/wave8/gtfsDe.js) serves a
 * pre-computed snapshot instead. THIS script is the only place the .pb is
 * ever downloaded: it runs in GitHub Actions (node: + the repo's `pbf`
 * decoder), decodes the feed with a hand-rolled GTFS-RT TripUpdate/Alert
 * reader, extracts the most-delayed trips and the active service alerts,
 * validates the result, and publishes it to the `gtfs-de-latest` GitHub
 * release on Sheldondouthat/satwq-reality-os:
 *
 *   gtfs-de-latest.json — {format, fetchedAt, feedTimestamp, counts, topDelayed, alerts}
 *   gtfs-de-meta.json   — provenance for the snapshot pipeline itself
 *
 * ANY failure exits non-zero BEFORE the release is touched, so the last good
 * snapshot stays live. This script never writes synthetic transit data: if
 * the gtfs.de upstream is unreachable it reports the exact error and exits 1.
 *
 * The live file regenerates ~every 10 s, so a download can race the
 * regeneration (curl exit 18: declared length vs regenerated bytes). The
 * downloader retries with backoff and re-validates the decode; a truncated
 * protobuf that still parses is rejected by entity-count sanity checks.
 *
 * Usage:
 *   node scripts/gtfs-de-snapshot.mjs [--top-delayed 100] [--max-alerts 50]
 *     [--retries 5] [--dry-run] [--out-dir /tmp/gtfs-de-snap]
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { PbfReader } from 'pbf';
import {
  buildGtfsDeSnapshot,
  validateGtfsDeSnapshot,
} from '../server/providers/wave8/gtfsDe.js';

const REPO = 'Sheldondouthat/satwq-reality-os';
const TAG = 'gtfs-de-latest';
const FEED_URL = 'https://realtime.gtfs.de/realtime-free.pb';
const FETCH_TIMEOUT_MS = 180_000;
const FEED_CAP_BYTES = 64 * 1024 * 1024; // feed is ~9–14 MB; 64 MB is a hard ceiling
const SNAPSHOT_CAP_BYTES = 512 * 1024;
const MAX_STRING_CHARS = 256; // GTFS ids/labels are short; over-long fields are refused
const MAX_ENTITIES = 300_000; // feed measured ~214k entities on 2026-10-05 (up from ~30k when the cap was set) — growth is real, not corruption; revisit the cap if the upstream keeps growing
const MAX_STU_PER_TRIP = 2_000; // a trip has tens of stops; beyond this the record is corrupt
const MAX_ALERT_SELECTORS = 500; // informed_entity[] per alert
const MAX_TRANSLATIONS = 20; // translation[] per TranslatedString
const USER_AGENT = 'SATWQ-Reality-OS/1.0 (gtfs.de snapshot pipeline)';

const fail = (message) => {
  console.error(`[gtfs-de-snapshot] FATAL: ${message}`);
  process.exit(1);
};

const usage = () => `Usage: node scripts/gtfs-de-snapshot.mjs [options]
  --top-delayed INT  most-delayed trips to keep, 1..1000 (default: 100)
  --max-alerts INT   service alerts to keep, 1..500 (default: 50)
  --retries INT      download attempts, 1..10 (default: 5)
  --dry-run          run the full pipeline but do not touch the GitHub release
  --out-dir PATH     snapshot output directory (default: /tmp/gtfs-de-snap)`;

/** Strict argv parsing: unknown flags and bad values exit 2 with usage. */
export function parseArgs(argv) {
  const opts = {
    topDelayed: 100,
    maxAlerts: 50,
    retries: 5,
    dryRun: false,
    outDir: '/tmp/gtfs-de-snap',
  };
  const intOpt = (arg, raw, min, max) => {
    if (!/^\d+$/.test(raw))
      throw new Error(`${arg} must be an integer, got "${raw}"`);
    const v = Number(raw);
    if (v < min || v > max)
      throw new Error(`${arg} must be ${min}..${max}, got ${v}`);
    return v;
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const next = () => {
      const v = argv[i + 1];
      if (v === undefined || v.startsWith('--')) {
        throw new Error(`missing value for ${arg}`);
      }
      i++;
      return v;
    };
    if (arg === '--top-delayed') {
      opts.topDelayed = intOpt(arg, next(), 1, 1000);
    } else if (arg === '--max-alerts') {
      opts.maxAlerts = intOpt(arg, next(), 1, 500);
    } else if (arg === '--retries') {
      opts.retries = intOpt(arg, next(), 1, 10);
    } else if (arg === '--dry-run') {
      opts.dryRun = true;
    } else if (arg === '--out-dir') {
      opts.outDir = next();
    } else if (arg === '--help' || arg === '-h') {
      console.log(usage());
      process.exit(0);
    } else {
      throw new Error(`unknown argument "${arg}"`);
    }
  }
  return opts;
}

/** Run gh; throws with the command's stderr on failure. */
function gh(...args) {
  try {
    return execFileSync('gh', [...args, '--repo', REPO], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch (error) {
    const stderr = error.stderr?.toString().trim() || error.message;
    throw new Error(`gh ${args.join(' ')} failed: ${stderr}`);
  }
}

// ——— GTFS-RT TripUpdate/Alert decoder (field numbers per gtfs-realtime.proto) ———
// FeedMessage: 1 header, 2 entity[] · FeedHeader: 1 version, 3 timestamp
// FeedEntity: 1 id, 2 is_deleted, 3 trip_update, 5 alert
// TripUpdate: 1 trip, 2 stop_time_update[], 5 delay
// TripDescriptor: 1 trip_id, 2 start_time, 3 start_date, 5 route_id
// StopTimeUpdate: 1 stop_sequence, 2 arrival, 3 departure, 4 stop_id
// StopTimeEvent: 1 delay (int32, signed — negative = ahead of schedule)
// Alert: 5 informed_entity[], 6 cause, 7 effect, 10 header_text, 11 description_text
// TranslatedString: 1 translation[] · Translation: 1 text, 2 language
// EntitySelector: 1 agency_id, 2 route_id

function readBoundedString(pbf, target) {
  const value = pbf.readString();
  if (value.length <= MAX_STRING_CHARS) return value;
  target.oversize = true;
  return null;
}

function readTranslation(tag, o, pbf) {
  if (tag === 1) o.text = readBoundedString(pbf, o);
  else if (tag === 2) o.lang = readBoundedString(pbf, o);
}

function readTranslatedString(tag, o, pbf) {
  if (tag === 1) {
    const t = pbf.readMessage(readTranslation, {});
    if (t.text != null) {
      (o.translations ??= []).push(t);
      if (o.translations.length > MAX_TRANSLATIONS) o.oversize = true;
    }
  }
}

/** First translation text (prefers German, else first available). */
function textOf(ts) {
  const list = ts?.translations ?? [];
  if (!list.length) return '';
  return list.find((t) => t.lang === 'de')?.text ?? list[0].text ?? '';
}

function readStopTimeEvent(tag, o, pbf) {
  // delay is int32: negative values arrive as 10-byte sign-extended varints,
  // so readVarint(true) reinterprets them as signed.
  if (tag === 1) o.delay = pbf.readVarint(true);
}

function readStopTimeUpdate(tag, o, pbf) {
  if (tag === 1) o.stopSequence = pbf.readVarint();
  else if (tag === 2) o.arrival = pbf.readMessage(readStopTimeEvent, {});
  else if (tag === 3) o.departure = pbf.readMessage(readStopTimeEvent, {});
  else if (tag === 4) o.stopId = readBoundedString(pbf, o);
}

function readTripDescriptor(tag, o, pbf) {
  if (tag === 1) o.tripId = readBoundedString(pbf, o);
  else if (tag === 2) o.startTime = readBoundedString(pbf, o);
  else if (tag === 3) o.startDate = readBoundedString(pbf, o);
  else if (tag === 5) o.routeId = readBoundedString(pbf, o);
}

function readTripUpdate(tag, o, pbf) {
  if (tag === 1) o.trip = pbf.readMessage(readTripDescriptor, {});
  else if (tag === 2) {
    const stu = pbf.readMessage(readStopTimeUpdate, {});
    (o.stopTimeUpdates ??= []).push(stu);
  } else if (tag === 5) o.delay = pbf.readVarint(true); // int32, signed
}

function readEntitySelector(tag, o, pbf) {
  if (tag === 1) o.agencyId = readBoundedString(pbf, o);
  else if (tag === 2) o.routeId = readBoundedString(pbf, o);
}

function readAlert(tag, o, pbf) {
  if (tag === 5) {
    const sel = pbf.readMessage(readEntitySelector, {});
    (o.informed ??= []).push(sel);
    if (o.informed.length > MAX_ALERT_SELECTORS) o.oversize = true;
  } else if (tag === 6) o.cause = pbf.readVarint();
  else if (tag === 7) o.effect = pbf.readVarint();
  else if (tag === 10) o.header = pbf.readMessage(readTranslatedString, {});
  else if (tag === 11)
    o.description = pbf.readMessage(readTranslatedString, {});
}

function readFeedEntity(tag, entity, pbf) {
  if (tag === 1) entity.id = readBoundedString(pbf, entity);
  else if (tag === 2) entity.isDeleted = pbf.readBoolean();
  else if (tag === 3) entity.tripUpdate = pbf.readMessage(readTripUpdate, {});
  else if (tag === 5) entity.alert = pbf.readMessage(readAlert, {});
  // tag 4 (vehicle) is skipped: this feed carries no VehiclePositions, and
  // pbf advances past any tag the reader leaves untouched.
}

function readFeedHeader(tag, header, pbf) {
  if (tag === 1) header.version = readBoundedString(pbf, header);
  else if (tag === 3) header.timestamp = pbf.readVarint();
}

function readFeedMessage(tag, message, pbf) {
  if (tag === 1) message.header = pbf.readMessage(readFeedHeader, {});
  else if (tag === 2)
    message.entities.push(pbf.readMessage(readFeedEntity, {}));
}

/**
 * Decode a gtfs.de realtime-free GTFS-RT feed into plain JS.
 * Returns { feedTimestamp, entities } where each entity is
 * { id, isDeleted, tripUpdate?, alert? } with oversize-flagged records
 * dropped (a truncated id is a different trip, not a shorter name for it).
 */
export function decodeGtfsRtFeed(bytes) {
  const view = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  const pbf = new PbfReader(view);
  const message = pbf.readFields(readFeedMessage, { header: {}, entities: [] });
  const feedTimestamp =
    Number.isFinite(message.header?.timestamp) && message.header.timestamp > 0
      ? new Date(message.header.timestamp * 1000).toISOString()
      : null;
  if (!feedTimestamp) {
    throw new Error(
      'gtfs_rt_decode_invalid: feed header has no usable timestamp',
    );
  }
  const entities = [];
  if (message.entities.length > MAX_ENTITIES) {
    throw new Error(
      `gtfs_rt_decode_invalid: ${message.entities.length} entities exceeds cap ${MAX_ENTITIES}`,
    );
  }
  for (const e of message.entities) {
    if (e.oversize) continue;
    const entity = { id: e.id ?? null, isDeleted: e.isDeleted === true };
    if (e.tripUpdate) {
      const tu = e.tripUpdate;
      if (tu.oversize || tu.trip?.oversize) continue;
      if ((tu.stopTimeUpdates ?? []).length > MAX_STU_PER_TRIP) continue;
      const stopTimeUpdates = [];
      let bad = false;
      for (const stu of tu.stopTimeUpdates ?? []) {
        if (stu.oversize) {
          bad = true;
          break;
        }
        stopTimeUpdates.push({
          stopId: stu.stopId ?? null,
          stopSequence: Number.isInteger(stu.stopSequence)
            ? stu.stopSequence
            : null,
          arrivalDelay: Number.isInteger(stu.arrival?.delay)
            ? stu.arrival.delay
            : null,
          departureDelay: Number.isInteger(stu.departure?.delay)
            ? stu.departure.delay
            : null,
        });
      }
      if (bad) continue;
      entity.tripUpdate = {
        trip: {
          tripId: tu.trip?.tripId ?? null,
          routeId: tu.trip?.routeId ?? null,
          startDate: tu.trip?.startDate ?? null,
        },
        delay: Number.isInteger(tu.delay) ? tu.delay : null,
        stopTimeUpdates,
      };
    }
    if (e.alert && !e.alert.oversize) {
      const a = e.alert;
      const routes = [];
      const agencyIds = [];
      for (const sel of a.informed ?? []) {
        if (sel.routeId) routes.push(sel.routeId);
        if (sel.agencyId) agencyIds.push(sel.agencyId);
      }
      entity.alert = {
        header: textOf(a.header).slice(0, MAX_STRING_CHARS),
        description: textOf(a.description).slice(0, MAX_STRING_CHARS),
        cause: Number.isInteger(a.cause) ? a.cause : null,
        effect: Number.isInteger(a.effect) ? a.effect : null,
        routes: [...new Set(routes)].slice(0, 50),
        agencyIds: [...new Set(agencyIds)].slice(0, 50),
      };
    }
    if (entity.tripUpdate || entity.alert || entity.isDeleted)
      entities.push(entity);
  }
  return { feedTimestamp, entities };
}

/** Single download attempt: transport errors throw; the caller decides retries. */
async function downloadOnce(url, { capBytes }) {
  const controller = new AbortController();
  const timer = setTimeout(
    () => controller.abort(new Error('fetch timed out')),
    FETCH_TIMEOUT_MS,
  );
  try {
    const res = await fetch(url, {
      signal: controller.signal,
      redirect: 'follow',
      headers: {
        'User-Agent': USER_AGENT,
        Accept: 'application/octet-stream',
      },
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const declared = Number(res.headers.get('content-length'));
    if (Number.isFinite(declared) && declared > capBytes) {
      throw new Error(
        `declared content-length ${declared} exceeds cap ${capBytes}`,
      );
    }
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length > capBytes)
      throw new Error(`body exceeded cap ${capBytes} bytes`);
    if (buf.length < 1024)
      throw new Error(`suspiciously small body (${buf.length} bytes)`);
    return buf;
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Fetch + decode + build + validate as ONE retried unit. The feed
 * regenerates ~every 10 s, so a download can race regeneration: the transport
 * can succeed while the bytes are a truncated protobuf that fails decode,
 * parses to an implausibly small entity set, or builds a snapshot that fails
 * validation. Retrying only the transport (or worse, exiting 1 on a decode
 * failure) leaves a good feed one regeneration away — so a decode failure,
 * an implausibly low entity count, or a build/validation failure retries the
 * entire bounded download with backoff.
 */
async function fetchBuildValidate({ retries, buildOpts }) {
  let lastError = null;
  for (let attempt = 1; attempt <= retries; attempt++) {
    console.log(
      `[gtfs-de-snapshot] fetch+decode attempt ${attempt}/${retries}…`,
    );
    let feedBytes;
    try {
      feedBytes = await downloadOnce(FEED_URL, { capBytes: FEED_CAP_BYTES });
    } catch (error) {
      lastError = error;
      console.log(
        `[gtfs-de-snapshot] attempt ${attempt} download failed: ${error.message}`,
      );
      if (attempt < retries)
        await new Promise((r) => setTimeout(r, 2000 * attempt));
      continue;
    }
    console.log(
      `[gtfs-de-snapshot] downloaded ${(feedBytes.length / 1048576).toFixed(1)} MB`,
    );
    try {
      const decoded = decodeGtfsRtFeed(feedBytes);
      if (decoded.entities.length < 100) {
        throw new Error(
          `entity count ${decoded.entities.length} implausibly low for this feed — refusing to publish`,
        );
      }
      console.log(
        `[gtfs-de-snapshot] decoded ${decoded.entities.length} entities, feed time ${decoded.feedTimestamp}`,
      );
      // buildGtfsDeSnapshot validates internally; a corrupt-but-parseable
      // feed that fails here is retried like a decode failure.
      const snapshot = buildGtfsDeSnapshot(decoded, buildOpts);
      return { feedBytes, decoded, snapshot };
    } catch (error) {
      lastError = error;
      console.log(
        `[gtfs-de-snapshot] attempt ${attempt} decode/build failed: ${error.message} — retrying whole download`,
      );
      if (attempt < retries)
        await new Promise((r) => setTimeout(r, 2000 * attempt));
    }
  }
  throw lastError;
}

async function main() {
  let opts;
  try {
    opts = parseArgs(process.argv.slice(2));
  } catch (error) {
    console.error(`[gtfs-de-snapshot] ${error.message}\n${usage()}`);
    process.exit(2);
  }
  console.log(
    `[gtfs-de-snapshot] top-delayed=${opts.topDelayed} max-alerts=${opts.maxAlerts}` +
      (opts.dryRun ? ' DRY-RUN (no release publish)' : ''),
  );

  const fetchedAt = new Date().toISOString();
  const { feedBytes, decoded, snapshot } = await fetchBuildValidate({
    retries: opts.retries,
    buildOpts: {
      fetchedAt,
      topN: opts.topDelayed,
      maxAlerts: opts.maxAlerts,
    },
  }).catch((e) =>
    fail(
      `feed fetch+decode+build failed after ${opts.retries} attempts: ${e.message}`,
    ),
  );

  console.log(
    `[gtfs-de-snapshot] snapshot: ${snapshot.counts.tripUpdates} trip updates, ` +
      `${snapshot.counts.alerts} alerts, top delay ${snapshot.topDelayed[0]?.delaySec ?? 0}s`,
  );

  mkdirSync(opts.outDir, { recursive: true });
  const snapPath = path.join(opts.outDir, 'gtfs-de-latest.json');
  const metaPath = path.join(opts.outDir, 'gtfs-de-meta.json');
  const snapBytes = new TextEncoder().encode(JSON.stringify(snapshot));
  if (snapBytes.length > SNAPSHOT_CAP_BYTES) {
    fail(`snapshot too large for edge: ${snapBytes.length} bytes`);
  }
  writeFileSync(snapPath, snapBytes);
  const meta = {
    pipeline: 'scripts/gtfs-de-snapshot.mjs',
    feedBytes: feedBytes.length,
    feedTimestamp: decoded.feedTimestamp,
    counts: snapshot.counts,
    fetchedAt,
    snapshotBytes: snapBytes.length,
    generatedAt: new Date().toISOString(),
  };
  writeFileSync(metaPath, JSON.stringify(meta, null, 2));

  // Read-back verification: the bytes we are about to publish must be exactly
  // what the edge provider validates.
  try {
    if (statSync(snapPath).size !== snapBytes.length) {
      throw new Error('gtfs-de-latest.json size mismatch on read-back');
    }
    const back = JSON.parse(readFileSync(snapPath, 'utf8'));
    validateGtfsDeSnapshot(back);
    if (back.feedTimestamp !== decoded.feedTimestamp) {
      throw new Error('feedTimestamp mismatch on read-back');
    }
  } catch (error) {
    fail(`snapshot verification failed: ${error.message}`);
  }
  console.log(
    `[gtfs-de-snapshot] snapshot verified locally (${snapBytes.length} bytes).`,
  );

  publishRelease({ snapPath, metaPath, dryRun: opts.dryRun });
}

/**
 * Publish the snapshot assets to the GitHub release. Exported for tests:
 * pass dryRun:true and a recording runGh to prove a dry run can never
 * invoke gh. Production main() passes no runGh, so the real gh runs.
 */
export function publishRelease({ snapPath, metaPath, dryRun, runGh = gh }) {
  if (dryRun) {
    console.log('[gtfs-de-snapshot] dry-run: skipping release publish.');
    console.log(`[gtfs-de-snapshot] files: ${snapPath}, ${metaPath}`);
    return { published: false };
  }

  // ---- From here on every step mutates the release; all prior steps passed.
  let releaseExists = true;
  try {
    runGh('release', 'view', TAG);
  } catch {
    releaseExists = false;
  }
  if (!releaseExists) {
    console.log(`[gtfs-de-snapshot] creating release ${TAG}…`);
    try {
      runGh(
        'release',
        'create',
        TAG,
        '--title',
        'gtfs.de realtime transit snapshot (latest)',
        '--notes',
        'Latest gtfs.de realtime-free GTFS-RT snapshot for the Cloudflare Pages deploy. ' +
          'Refreshed by scripts/gtfs-de-snapshot.mjs; gtfs-de-latest.json holds the most-delayed ' +
          'trips and active service alerts. Source data: gtfs.de (CC BY-SA 4.0).',
      );
    } catch (error) {
      fail(error.message);
    }
  }
  console.log('[gtfs-de-snapshot] uploading assets (--clobber)…');
  try {
    runGh('release', 'upload', TAG, snapPath, metaPath, '--clobber');
  } catch (error) {
    fail(error.message);
  }
  const base = `https://github.com/${REPO}/releases/download/${TAG}`;
  console.log('[gtfs-de-snapshot] published:');
  console.log(`  ${base}/gtfs-de-latest.json`);
  console.log(`  ${base}/gtfs-de-meta.json`);
  return { published: true };
}

const invokedPath = process.argv[1]
  ? pathToFileURL(path.resolve(process.argv[1])).href
  : '';
if (import.meta.url === invokedPath) {
  await main();
}
