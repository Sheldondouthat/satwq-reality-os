const REGIONAL_OVERRIDE = { ALS: [-150.0, 64.0], HWA: [-157.8, 20.8] };

/** [lon, lat] or null when the code cannot be placed on a globe. */
export function centroidFor(code) {
  if (!code) return null;
  const up = String(code).trim().toUpperCase();
  if (REGIONAL_OVERRIDE[up]) return REGIONAL_OVERRIDE[up];
  const iso = ITU_TO_ISO2[up] ?? (/^[A-Z]{2}$/.test(up) ? up : null);
  if (!iso) return null;
  return COUNTRY_CENTROIDS[iso] ?? null;
}
